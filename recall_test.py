# Файл: recall_test.py
# Замер полноты поиска (Recall) для узла arxiv_searcher.
# Печатает ДВЕ метрики по каждой теме и в итоге:
#   Recall@6  — «боевой» режим: в проде MAX_PAPERS = 6, система забирает только топ-6 кандидатов;
#   Recall@25 — «глубокий» режим: диагностический потолок поисковика по топ-25 кандидатам.
# Запуск: python recall_test.py  (займёт 15-30 минут — качает PDF, не прерывать!)

import arxiv_searcher as S

TOPICS = [
    ("Mitigating hallucination in LLM-based literature review", ["2411.14199", "2309.11495", "2303.08896"]),
    ("Evaluating RAG systems with LLM-as-a-judge", ["2306.05685", "2309.15217", "2304.09848"]),
    ("Retrieval augmented generation for scientific literature review", ["2312.07559", "2402.01720"]),
    ("Survey on hallucination in large language models", ["2311.05232", "2309.01219", "2202.03629"]),
    ("Survey on retrieval augmented generation for large language models", ["2312.10997", "2202.01110"]),
    ("Query expansion and query rewriting for retrieval with LLMs", ["2305.03653", "2212.10496"]),
    ("Verifying citations and quotations generated by LLMs", ["2304.09848", "2309.01431"]),
    ("Re-ranking retrieved documents with large language models", ["2304.09542", "2307.03172"]),
    ("Knowledge graph enhanced retrieval augmented generation", ["2404.16130", "2308.11741"]),
    ("Self-reflective and corrective retrieval augmented generation", ["2310.11511", "2401.15884"]),
    ("Chunking and retrieval granularity for RAG", ["2312.06648"]),
    ("LLM feedback on scientific papers and peer review", ["2310.01783"]),
]

K_BATTLE = 6    # боевой лимит: столько статей реально забирает система (MAX_PAPERS в проде)
K_DEEP = 25     # глубина диагностического прогона

S.MAX_PAPERS = K_DEEP   # делаем ОДИН глубокий прогон на тему (в бою хватает 6)

hits6 = hits25 = total = 0
for query, expected in TOPICS:
    out = S.arxiv_search_node({"user_query": query, "search_queries": [query], "found_papers": []})
    # found_papers идут в порядке обхода кандидатов, поэтому топ-6 — это просто первые 6
    # из глубокого прогона: отдельный прогон с MAX_PAPERS=6 дал бы тот же набор.
    found_ids = [S.clean_id(p.arxiv_id) for p in out["found_papers"]]
    exp = [S.clean_id(e) for e in expected]
    ok6 = sum(1 for e in exp if e in found_ids[:K_BATTLE])
    ok25 = sum(1 for e in exp if e in found_ids)
    hits6 += ok6
    hits25 += ok25
    total += len(exp)
    print(f"Recall@{K_BATTLE} = {ok6}/{len(exp)} = {ok6/len(exp):.2f} | "
          f"Recall@{K_DEEP} = {ok25}/{len(exp)} = {ok25/len(exp):.2f}   {query[:60]}")

print(f"\nИТОГО Recall@{K_BATTLE}  = {hits6}/{total} = {hits6/total:.2f}")
print(f"ИТОГО Recall@{K_DEEP} = {hits25}/{total} = {hits25/total:.2f}")
print("\nКак читать: Recall@6 близок к нулю НЕ потому, что поиск плохой. Кандидаты из OpenAlex "
      "дописываются в список после round-robin по arXiv, а в боевую выборку попадают первые "
      f"{K_BATTLE} (MAX_PAPERS), поэтому эталонные статьи, найденные только через OpenAlex, "
      "физически не успевают попасть в топ-6. Recall@25 показывает потолок того же поисковика. "
      "Лечится перестановкой кандидатов в arxiv_searcher._candidate_ids — осознанно отложено, "
      "чтобы не ломать сопоставимость с уже снятыми цифрами бенчмарка.")
